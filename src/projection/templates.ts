import { recordReference } from "../domain/references.js";
import type {
  EvidenceReference,
  RecordKind,
  SemanticRecord,
  ValidatedRepository,
} from "../domain/types.js";

const marker = "<!-- Generated by LORE. Do not edit directly. -->";
const esc = (value: string) => value.replace(/\|/g, "\\|").replace(/#/g, "\\#");
const active = (record: SemanticRecord, repository: ValidatedRepository) =>
  repository.effectiveStatus.get(
    recordReference(repository.manifest.repository.id, record),
  ) !== "superseded";

const records = (
  repository: ValidatedRepository,
  kind: RecordKind,
): SemanticRecord[] =>
  repository.records
    .filter((record) => record.kind === kind && active(record, repository))
    .sort((left, right) =>
      left.title.localeCompare(right.title) || left.id.localeCompare(right.id),
    );

const firstRecord = (
  repository: ValidatedRepository,
  kind: RecordKind,
): SemanticRecord | undefined => records(repository, kind)[0];

const evidenceLabel = (evidence: EvidenceReference): string => {
  const location = evidence.symbol
    ? `${evidence.path}#${evidence.symbol}`
    : evidence.lines
      ? `${evidence.path}#L${evidence.lines.start}-L${evidence.lines.end}`
      : evidence.path;
  return `\`${location}\` at \`${evidence.revision}\``;
};

const renderEvidence = (record: SemanticRecord): string =>
  record.evidence.length === 0
    ? "Evidence: none recorded."
    : `Evidence: ${record.evidence.map(evidenceLabel).join(", ")}.`;

const renderRecordList = (
  selected: SemanticRecord[],
  emptyMessage: string,
): string =>
  selected.length === 0
    ? emptyMessage
    : selected
        .map(
          (record) =>
            `- **${esc(record.title)}:** ${record.summary} ${renderEvidence(record)}`,
        )
        .join("\n");

const renderRecordSections = (
  selected: SemanticRecord[],
  emptyMessage: string,
  headingLevel = 2,
): string =>
  selected.length === 0
    ? emptyMessage
    : selected
        .map(
          (record) =>
            `${"#".repeat(headingLevel)} ${esc(record.title)}\n\n${record.summary}\n\n${renderEvidence(record)}\n`,
        )
        .join("\n");

