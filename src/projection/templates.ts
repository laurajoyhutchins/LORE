export function renderDataModelReference(repository: ValidatedRepository) {
  return `${marker}
# Data model reference

LORE keeps deterministic observations, reviewed interpretations, candidate changes, accepted transactions, and generated views separate.

## Manifest

\`lore.yaml\` declares repository identity, owned paths, enabled extractors, deterministic projections, the maintainer skill, the proposal schema, and hydration limits. Unknown schema versions and projection IDs fail closed.

## Semantic record envelope

Every accepted record has a stable ID, kind, positive revision, immutable status, title, summary, scope, exact Git evidence, disclosure metadata, provenance, optional supersession reference, and a payload object. Schema version 1 reserves payload meaning for each record kind without yet imposing kind-specific payload sub-schemas.

| Kind | Purpose |
|---|---|
| \`repository\` | Repository purpose, boundaries, entry points, and support state |
| \`component\` | Responsibilities, owned paths, interfaces, dependencies, and invariants |
| \`relationship\` | A typed connection among accepted records or extracted components |
| \`decision\` | A chosen design with rationale, alternatives, and consequences |
| \`finding\` | A verified defect, limitation, risk, or technical-debt item |
| \`constraint\` | A rule that must remain true across implementation and operation |
| \`procedure\` | A repeatable workflow with prerequisites, steps, expected results, and failure handling |

Accepted revisions live beneath \`${repository.manifest.paths.records}/<kind>/<id>/<revision>.yaml\`. Corrections append a new revision and preserve lineage through \`supersedes\`.

## Evidence references

Evidence uses a full 40-character Git commit SHA plus a repository-relative path. A reference may add a symbol or validated line range. Generated prose cannot be the sole evidence for a semantic assertion.

## Task and hydration

A task declares an ID, title, description, paths, component IDs, tags, audiences, and whether superseded history is eligible. Hydration scores records deterministically, reports selection reasons, includes direct evidence, and reports omitted records.

## Maintainer context and proposal

\`lore-maintainer-context/v1\` wraps the validated task, hydration packet, skill path, output schema, and proposal destination. A \`lore-proposal/v1\` artifact returns either candidate operations or a first-class no-change result.

## Transaction receipt

An accepted proposal writes new immutable record revisions, a transaction receipt beneath \`${repository.manifest.paths.transactions}/\`, and regenerated projections. Application plans the complete candidate state before writing and rolls back failed writes.

## Projection

Generated Markdown begins with the LORE marker, contains no current time or machine-specific absolute paths, uses stable ordering, and must be byte-identical for unchanged authoritative inputs.
`;
}
